/* standard Graphics I: LCG-filled tables, sprites from LCG attribute data */
static void sceneGraphicsI(void)
{
  lcgSeed(0x1001);
  vramFillLcg(0x0000, 0x4000);
  regWrite(0, 0x00);
  regWrite(1, 0xe0); /* 16K, display on, int enable */
  regWrite(2, 0x0e); /* name table    0x3800 */
  regWrite(3, 0x00); /* color table   0x0000 */
  regWrite(4, 0x04); /* pattern table 0x2000 */
  regWrite(5, 0x76); /* sprite attrs  0x3b00 */
  regWrite(6, 0x03); /* sprite patts  0x1800 */
  regWrite(7, 0xf9); /* white on light red - backdrop low nibble >= 8 pins
                        the full 4-bit backdrop colour mask */
}

/* standard Graphics II (bitmap): three pattern/color pages */
static void sceneGraphicsII(void)
{
  lcgSeed(0x2002);
  vramFillLcg(0x0000, 0x4000);
  regWrite(0, 0x02);
  regWrite(1, 0xe0);
  regWrite(2, 0x0e); /* name table    0x3800 */
  regWrite(3, 0xff); /* color table   0x2000, full name mask */
  regWrite(4, 0x03); /* pattern table 0x0000, all pages */
  regWrite(5, 0x76);
  regWrite(6, 0x03);
  regWrite(7, 0x01); /* bg black */
}

