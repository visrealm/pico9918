/* F18A unlocked: BML priority (VR31 bit 0x40 write-mask) with a width-64
 * fully-opaque band - drives the fast path that pre-fills the row mask and
 * suppresses both tile layers - over ECM2 tiles with ECM1 sprites placed to
 * cross the band edges (sprites render below the bitmap stage's mask but
 * still overdraw its pixels) */
static void sceneF18aBmlPriority(void)
{
  static const uint8_t sat[] = {
    /*  y,    x, name, color */
    0x10, 0x20, 0x01, 0x06,  /* above the band                */
    0x2c, 0x10, 0x00, 0x03,  /* crosses the band top (48)     */
    0x50, 0x58, 0x04, 0x05,  /* fully inside the band         */
    0x6c, 0xa0, 0x08, 0x07,  /* crosses the band bottom (112) */
    0xd0, 0x00, 0x00, 0x00   /* terminator */
  };

  lcgSeed(0xb00b);
  vramFillLcg(0x0000, 0x4000);
  vramWriteBytes(0x3b00, sat, (int)sizeof(sat));
  unlockF18a();
  regWrite(0, 0x00);
  regWrite(1, 0xe0);  /* display on, 8px sprites */
  regWrite(2, 0x0e);  /* T1 name  0x3800 */
  regWrite(3, 0x08);  /* T1 color 0x0200 */
  regWrite(4, 0x04);  /* pattern  0x2000 */
  regWrite(5, 0x76);  /* SAT      0x3b00 */
  regWrite(6, 0x03);  /* SPT      0x1800 */
  regWrite(7, 0xf4);
  regWrite(31, 0xc0); /* BML: enabled, priority/write-mask, opaque, 2bpp */
  regWrite(32, 0x20); /* BML addr 0x0800 */
  regWrite(33, 0x00); /* BML x = 0 (width-64 rows cover the full line) */
  regWrite(34, 0x30); /* BML top = 48 */
  regWrite(35, 0x00); /* BML width = 64 bytes (256px opaque) */
  regWrite(36, 0x40); /* BML height = 64 */
  regWrite(49, 0x21); /* ECM2 tiles | ECM1 sprites */
}

/* F18A unlocked ECM0: standard-format tiles through the scrolled F18A tile
 * path (renderEcm0Tile) with h-scroll shift==2 alignment, non-ECM sprites
 * rendered below the tile layer including a colour-0 transparent sprite
 * (its pixels must be released from the sprite mask so tiles show through),
 * and ReadData/read-ahead traffic feeding the sprite attribute table so the
 * data-port read behaviour influences pixels */
static void sceneF18aEcm0(void)
{
  lcgSeed(0xc00c);
  vramFillLcg(0x0000, 0x4000);
  unlockF18a();

  /* data-port read traffic: read 12 bytes back via read-ahead auto-increment
   * plus one ReadDataNoInc, then build sprites 0-3 from the values - any
   * change in read semantics moves/recolours the sprites */
  uint8_t rd[13];
  vramSetReadAddr(0x2600);
  for (int i = 0; i < 12; ++i) rd[i] = pico9918_read_data();
  rd[12] = pico9918_read_data_no_inc();

  uint8_t sat[8 * 4];
  for (int i = 0; i < 4; ++i)
  {
    sat[i * 4 + 0] = (uint8_t)(0x08 + i * 0x28); /* y: spread down the frame */
    sat[i * 4 + 1] = rd[i * 3];                  /* x from read data         */
    sat[i * 4 + 2] = rd[i * 3 + 1];              /* name from read data      */
    sat[i * 4 + 3] = rd[i * 3 + 2] & 0x0f;       /* colour from read data    */
  }
  /* sprite 4: solid; sprite 5: colour-0 transparent overlapping sprite 4
   * (overlap raises COL; its non-overlapped pixels enter then leave the
   * sprite mask, so the tiles beneath must render); sprite 6: name comes
   * from the ReadDataNoInc value */
  static const uint8_t satTail[] = {
    0x50, 0x40, 0x00, 0x05,
    0x50, 0x44, 0x01, 0x00,
    0x78, 0x80, 0x00, 0x0b,
    0xd0, 0x00, 0x00, 0x00
  };
  memcpy(sat + 16, satTail, sizeof(satTail));
  sat[26] = rd[12];  /* sprite 6 name from ReadDataNoInc */

  vramFillByte(0x1800, 0xff, 16);         /* sprite patterns 0 and 1: solid */
  vramFillByte(0x0000, 0x53, 32);         /* tile colours: fg 5 on bg 3 - every
                                             tile pixel is drawn, so masked-off
                                             pixels are always visible */
  vramWriteBytes(0x3b00, sat, (int)sizeof(sat));

  regWrite(0, 0x00);
  regWrite(1, 0xe0);  /* display on, 8px sprites */
  regWrite(2, 0x0e);  /* T1 name  0x3800 */
  regWrite(3, 0x00);  /* T1 color 0x0000 */
  regWrite(4, 0x04);  /* pattern  0x2000 */
  regWrite(5, 0x76);  /* SAT      0x3b00 */
  regWrite(6, 0x03);  /* SPT      0x1800 */
  regWrite(7, 0xf4);
  regWrite(27, 0x0a); /* T1 h-scroll: tile index 1, fine scroll 2 -> shift==2 */
  regWrite(49, 0x00); /* ECM0 tiles, non-ECM sprites */
}

/* F18A unlocked Graphics II: R0 GII bit set while unlocked takes the unlocked
 * Graphics-I path with the bitmap fetch paged (sprites, then the bitmap layer).
 * 16px sprites plus a transparent 2bpp BML window. */
static void sceneF18aGfx2(void)
{
  static const uint8_t sat[] = {
    /*  y,    x, name, color */
    0x20, 0x30, 0x00, 0x07,
    0x50, 0x80, 0x04, 0x0b,  /* inside the BML window */
    0x60, 0x40, 0x0c, 0x04,
    0x85, 0xc8, 0x08, 0x0d,  /* clips the right edge */
    0xd0, 0x00, 0x00, 0x00   /* terminator */
  };

  lcgSeed(0xd00d);
  vramFillLcg(0x0000, 0x4000);
  vramWriteBytes(0x3b00, sat, (int)sizeof(sat));
  unlockF18a();
  paletteWriteLcg(32);  /* rewrite half the palette - the pram dump pins it */
  regWrite(0, 0x02);  /* Graphics II while unlocked */
  regWrite(1, 0xe2);  /* display on, 16px sprites */
  regWrite(2, 0x0e);  /* name table  0x3800 */
  regWrite(3, 0xff);  /* color table 0x2000, full name mask */
  regWrite(4, 0x03);  /* pattern table 0x0000, all pages */
  regWrite(5, 0x76);  /* SAT 0x3b00 */
  regWrite(6, 0x03);  /* SPT 0x1800 */
  regWrite(7, 0xf1);
  regWrite(24, 0x02); /* T1 palette select 2 (GII applies it to tile colours) */
  regWrite(31, 0xa0); /* BML: enabled, transparent, 2bpp */
  regWrite(32, 0x30); /* BML addr 0x0c00 */
  regWrite(33, 0x40); /* BML x = 64 */
  regWrite(34, 0x20); /* BML top = 32 */
  regWrite(35, 0x40); /* BML width = 16 bytes (64px) */
  regWrite(36, 0x80); /* BML height = 128 */
}

/* raw-reset: pins the current post-reset contract. The scene itself
 * establishes a fully deterministic unlocked+configured state (VRAM, palette,
 * registers) and commits the unlocked mode by rendering a throwaway line,
 * then calls pico9918_reset() through the public API. The captured lines
 * are rendered WITHOUT the mode nudge sceneBegin() applies, so whatever the
 * reset path leaves behind (display off, backdrop 0, default palette, stale
 * cached mode) is golden-file contract - independent of scene order. */
static void sceneRawReset(void)
{
  lcgSeed(0xe00e);
  vramFillLcg(0x0000, 0x4000);
  unlockF18a();
  paletteWriteLcg(64);
  regWrite(0, 0x00);
  regWrite(1, 0xe0);
  regWrite(2, 0x0e);
  regWrite(7, 0x1f);
  regWrite(49, 0x11); /* ECM1 tiles | ECM1 sprites */
  pico9918_scan_line(0); /* commit the unlocked Graphics-I mode */
  pico9918_reset();
}

