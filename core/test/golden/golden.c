/* ---------------------------------------------------------------------------
 * Deterministic pseudo-random source (numerical recipes LCG)
 * ------------------------------------------------------------------------- */
static uint32_t lcgState;

static void lcgSeed(uint32_t seed)
{
  lcgState = seed;
}

static uint8_t lcgByte(void)
{
  lcgState = lcgState * 1664525u + 1013904223u;
  return (uint8_t)(lcgState >> 24);
}

/* ---------------------------------------------------------------------------
 * Bus helpers - the exact write paths the firmware uses (two-stage writes to
 * the address port, data-port writes with auto-increment)
 * ------------------------------------------------------------------------- */
static void regWrite(uint8_t reg, uint8_t value)
{
  pico9918_write_addr(value);
  pico9918_write_addr(0x80 | reg);
}

static void vramSetWriteAddr(uint16_t addr)
{
  pico9918_write_addr(addr & 0xff);
  pico9918_write_addr(0x40 | ((addr >> 8) & 0x3f));
}

/* set a read address: bit 6 clear in the second stage triggers the
 * read-ahead fetch (and its address auto-increment) */
static void vramSetReadAddr(uint16_t addr)
{
  pico9918_write_addr(addr & 0xff);
  pico9918_write_addr((addr >> 8) & 0x3f);
}

static void vramFillLcg(uint16_t addr, int count)
{
  vramSetWriteAddr(addr);
  while (count--) pico9918_write_data(lcgByte());
}

static void vramFillByte(uint16_t addr, uint8_t value, int count)
{
  vramSetWriteAddr(addr);
  while (count--) pico9918_write_data(value);
}

static void vramWriteBytes(uint16_t addr, const uint8_t* bytes, int count)
{
  vramSetWriteAddr(addr);
  while (count--) pico9918_write_data(*bytes++);
}

/* real F18A unlock sequence: VR57 = 0x1c written twice */
static void unlockF18a(void)
{
  regWrite(57, 0x1c);
  regWrite(57, 0x1c);
}

/* write count palette entries through the data-port palette mode (VR47).
 * exercises the two-stage palette write path; palette values do not affect
 * the indexed scanline output but ARE captured by the per-scene pram dump. */
static void paletteWriteLcg(int count)
{
  regWrite(47, 0xc0); /* data port palette mode, auto-increment, index 0 */
  while (count--)
  {
    pico9918_write_data(lcgByte() & 0x0f); /* 0R */
    pico9918_write_data(lcgByte());        /* GB */
  }
  regWrite(47, 0x00); /* leave palette mode */
}

/* ---------------------------------------------------------------------------
 * Scene lifecycle
 * ------------------------------------------------------------------------- */
static void sceneBegin(void)
{
  pico9918_reset();

  /* pico9918_reset() resets the cached display mode to Graphics I, but the
   * cache is only re-read on a mode CHANGE seen by pico9918_scan_line. Nudge
   * the mode register through Graphics II and back so it is re-resolved against
   * the now-locked state, making every scene independent of the one before it. */
  regWrite(0, 0x02);
  pico9918_scan_line(0);
  regWrite(0, 0x00);
  pico9918_scan_line(0);
}

/* Read the 64 live palette RAM entries (128 bytes) out through the public
 * bus API.
 *
 * The library exposes no palette read function, and every CPU-side read path
 * (data port, pico9918_vram_value) masks addresses to the 16K window
 * (0x3fff), so palette RAM at internal address 0x5000 cannot be read
 * directly. It IS reachable through the bitmap layer: the BML fetch address
 * (VR32 << 6) + row * width is not masked to 16K, so a width-64 opaque 2bpp
 * BML with VR32 = 0xff fetches bytes 0x5000..0x503f on scanline 65 and
 * 0x5040..0x507f on scanline 66 - the live pram - and emits each byte as
 * four 2-bit pixels (MSBs first). With both tile layers and sprites disabled
 * the scanline output is a byte-exact public read-out of the palette.
 *
 * Runs AFTER the scene's lines have been captured (it reprograms registers).
 * Everything here is deterministic, and every scene starts from
 * sceneBegin()'s reset, so no state leaks into the next scene. */
static void dumpPalette(uint8_t out[GOLDEN_PAL_BYTES])
{
  unlockF18a();
  regWrite(0, 0x00);  /* Graphics I */
  regWrite(1, 0x40);  /* display on */
  regWrite(7, 0x00);
  regWrite(49, 0x00); /* T2 off, no ECM, no 30-row */
  regWrite(50, 0x10); /* tile layer 1 off */
  regWrite(51, 0x00); /* sprites to process: 0 */
  regWrite(31, 0x80); /* BML: enabled, opaque, 2bpp, palette bits 0 */
  regWrite(32, 0xff); /* BML fetch base 0x3fc0 */
  regWrite(33, 0x00); /* BML x = 0 */
  regWrite(34, 0x00); /* BML top = 0 */
  regWrite(35, 0x00); /* BML width = 64 bytes (256px, full line) */
  regWrite(36, 0xff); /* BML height = 255 */

  for (int line = 0; line < 2; ++line)
  {
    pico9918_scan_line((uint16_t)(65 + line));
    const uint8_t* probe = pico9918_line_source();
    uint8_t* dst = out + line * 64;
    for (int i = 0; i < 64; ++i)
    {
      const uint8_t* p = probe + i * 4;
      dst[i] = (uint8_t)((p[0] << 6) | (p[1] << 4) | (p[2] << 2) | p[3]);
    }
  }
}

/* ---------------------------------------------------------------------------
 * Post-palette surfaces (format v3)
 *
 * The indexed scanline output is palette-independent, so nothing above this point
 * can observe the palette -> pixel conversion the library owns
 * (pico9918_palette.c). Each line is therefore ALSO expanded through the library's
 * own path and digested:
 *
 *   surface 0 "lib"   pico9918_palette_regenerate() + PICO9918_EXPAND_INDEXED,
 *                     i.e. the library's own path. One pixel policy ships and it
 *                     is the platform default, so this surface is the pixel
 *                     stream the device emits.
 *                     On its own this is self-capture: it pins the library
 *                     against itself and proves little.
 *
 *   surface 1 "ref"   the SAME indexed bytes and the SAME pram, expanded by
 *                     picoReferenceExpand() below - an INDEPENDENT
 *                     reimplementation of the documented pack formula and LUT
 *                     classing, written from the prose spec and deliberately
 *                     NOT calling PICO9918_PIXEL_FROM_RGB12 or
 *                     PICO9918_EXPAND_INDEXED. This is the evidence that the
 *                     formula is right rather than merely stable.
 *
 * Both surfaces are stored as 64-bit FNV-1a digests rather than raw pixels:
 * raw would be 1 KB per line (~3.5 MB of committed binaries) for no extra
 * diagnostic power, since a digest mismatch is localised to the exact pixel
 * by re-scanning the two buffers in memory (see reportPostPalette).
 *
 * Cross-check: the two surfaces now share a format, so they are compared
 * value-for-value on every line, every scene - any divergence between the
 * library's expansion and the independent reference fails the run before the
 * digests are even consulted. Their digests are stored SEPARATELY all the
 * same, so a change that moved both in lockstep (an edit to the reference
 * included) still shows up as a golden diff.
 * ------------------------------------------------------------------------- */

/* 64-bit FNV-1a */
#define FNV64_OFFSET 0xcbf29ce484222325ull
#define FNV64_PRIME  0x00000100000001b3ull

static uint64_t fnv1a(const void* data, size_t len)
{
  const uint8_t* p = (const uint8_t*)data;
  uint64_t h = FNV64_OFFSET;
  while (len--)
  {
    h ^= *p++;
    h *= FNV64_PRIME;
  }
  return h;
}

/* Independent reference for the pixel pack.
 *
 * Deliberately NOT PICO9918_PIXEL_FROM_RGB12 - this is the documented formula
 * rewritten from its prose description, so that breaking the macro diverges
 * from this and is caught:
 *
 *   a pram entry is byte-swapped RGB444 (0xGB0R): bits 15-12 = green,
 *   11-8 = blue, 7-4 = alpha-or-zero, 3-0 = red. The transform clears bits 7-4
 *   (stripping the alpha the palette-reset path deposits there) and copies
 *   GREEN down into them; blue and red stay put. Output is BGR12 in the low 12
 *   bits, with a dead copy of green in 15-12.
 *
 * Verified exhaustively equal to PICO9918_PIXEL_FROM_RGB12 over all 65536 inputs.
 * The channel names in the table above are load-bearing: a cross-check written from
 * the same prose as the macro's own comment cannot catch a shared misreading of the
 * format. See platform/pico/platform_pico.h.
 *
 * Written as explicit nibble extraction and reassembly rather than as the
 * library's mask/shift pair, so the two share no algebra. */
static uint16_t refPixel(uint16_t pram)
{
  const unsigned g = (pram >> 12) & 0x0f;  /* green - also copied into bits 7-4 */
  const unsigned b = (pram >>  8) & 0x0f;  /* blue */
  const unsigned r = (pram      ) & 0x0f;  /* red */
  return (uint16_t)((g << 12) | (b << 8) | (g << 4) | r);
}

/* one line of each surface - the expansion emits two pixels per indexed byte */
#define POST_PAL_PIXELS (GOLDEN_BYTES_PER_LINE * 2)

static PICO9918_PIXEL_T libPixels[POST_PAL_PIXELS];
static uint16_t       refPixels[POST_PAL_PIXELS];

/* The two surfaces are compared value-for-value, so the library's pixel type
   must match the reference's. If the shipped policy drifts to a wider pixel this
   fires here instead of surfacing as thousands of confusing digest mismatches.
   The LUT type is asserted for the same reason - the expansion indexes it as
   packed pairs. */
_Static_assert(sizeof(PICO9918_PIXEL_T) == sizeof(uint16_t),
               "golden surfaces require the 16-bit Pico pixel policy");
_Static_assert(sizeof(PICO9918_PALETTE_LUT_T) == sizeof(uint32_t),
               "golden expansion requires a 32-bit packed-pair LUT");

/* The reference's own LUT, as a pixel PAIR per entry like the library's.
 *
 * Kept as persistent state rather than rebuilt per line because the library's
 * LUT is persistent: it is global, rebuilt only when the palette is dirty, and
 * each rebuild is PARTIAL - the doubled build writes entries 0..63 only, since
 * doubled modes never index above 63. Entries 64..255 therefore survive from
 * whichever paired build last ran, across scene boundaries. Modelling that
 * faithfully is the whole point: f18a-text80-attrs really does render its
 * first line through entries text80 left behind, and a reference that rebuilt
 * from scratch would disagree with a perfectly correct library.
 *
 * Zero-initialised, matching pico9918_init() zeroing pico9918_palette_lut. */
static uint32_t refLut[256];

/* Independent reference for the LUT build - the counterpart of
 * pico9918_palette_regenerate(), written from the documented behaviour:
 *
 *   DOUBLED  entries 0..63, each the pram entry's pixel repeated in both
 *            halves of the word.
 *   PAIRED   entries 0..15 doubled (an index < 16 still means one colour),
 *            then 16..255 where the byte is two 4-bit indexes: the high
 *            nibble's colour in the low half of the word, the low nibble's in
 *            the high half. Little-endian storage puts the low half at the
 *            lower address, so the HIGH nibble is the left-hand pixel.
 *
 * Deliberately does not share code with the library's version. */
static void refRegenerate(bool paired)
{
  const uint16_t* pram = tms9918->vram.map.pram;

  if (!paired)
  {
    for (int i = 0; i < 64; ++i)
    {
      const uint32_t px = refPixel(pram[i]);
      refLut[i] = px | (px << 16);
    }
    return;
  }

  uint16_t pal[16];
  for (int i = 0; i < 16; ++i)
  {
    pal[i] = refPixel(pram[i]);
    refLut[i] = (uint32_t)pal[i] | ((uint32_t)pal[i] << 16);
  }
  for (int j = 16; j < 256; ++j)
  {
    refLut[j] = ((uint32_t)pal[j & 0x0f] << 16) | pal[j >> 4];
  }
}

/* Independent reference for the expansion - the counterpart of
 * PICO9918_EXPAND_INDEXED. Unpacks each LUT word into its two pixels so the
 * digest covers the per-pixel STREAM, making the pair-packing trick something
 * the goldens verify rather than assume. */
static void refExpand(uint16_t* dst, const uint8_t* src, int n)
{
  for (int i = 0; i < n; ++i)
  {
    const uint32_t entry = refLut[src[i]];
    dst[i * 2 + 0] = (uint16_t)entry;
    dst[i * 2 + 1] = (uint16_t)(entry >> 16);
  }
}

/* Expand one captured line through both surfaces and digest them. */
static void expandLine(const uint8_t* indexed, uint64_t digests[GOLDEN_DIGESTS_PER_LINE])
{
  PICO9918_EXPAND_INDEXED(libPixels, indexed, GOLDEN_BYTES_PER_LINE, pico9918_palette_lut);
  refExpand(refPixels, indexed, GOLDEN_BYTES_PER_LINE);

  digests[0] = fnv1a(libPixels, sizeof(libPixels));
  digests[1] = fnv1a(refPixels, sizeof(refPixels));
}

/* First position where the library expansion and the independent reference
 * disagree, or -1. Both are BGR16 under the golden pixel policy, so this is a
 * direct value comparison - the strongest form of the cross-check. */
static int refDivergence(void)
{
  for (int i = 0; i < POST_PAL_PIXELS; ++i)
  {
    if (libPixels[i] != refPixels[i]) return i;
  }
  return -1;
}

