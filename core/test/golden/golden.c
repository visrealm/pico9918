/* TEXT80 (F18A 80-column), locked, two-tone path.
 * output packing is two 4-bit pixels per byte - part of the contract. */
static void sceneText80(void)
{
  lcgSeed(0x5005);
  vramFillLcg(0x0000, 0x4000);
  regWrite(0, 0x04); /* TEXT80 mode bit */
  regWrite(1, 0xd0);
  regWrite(2, 0x0c); /* name table 0x3000 (locked mask 0x0c) */
  regWrite(4, 0x01); /* pattern table 0x0800 */
  regWrite(7, 0xf4);
}

/* hand-placed standard sprites: five sprites on one row raise the
 * 5th-sprite status flag; an overlapping pair raises coincidence. */
static void sceneSpritesMax(void)
{
  static const uint8_t sat[] = {
    /*  y,    x, name, color */
    0x27, 0x00, 0x00, 0x02,  /* row 40: sprites 0..4              */
    0x27, 0x28, 0x00, 0x03,
    0x27, 0x50, 0x00, 0x04,
    0x27, 0x78, 0x00, 0x05,
    0x27, 0xa0, 0x00, 0x06,  /* 5th sprite on the line -> 5S flag */
    0x63, 0x64, 0x00, 0x08,  /* row 100: overlapping pair -> COL  */
    0x63, 0x68, 0x01, 0x09,  /* solid 100..107 vs half 104..107   */
    0xd0, 0x00, 0x00, 0x00   /* terminator */
  };

  vramFillByte(0x0000, 0x00, 0x4000);
  vramFillByte(0x1800, 0xff, 8);        /* sprite pattern 0: solid   */
  vramFillByte(0x1808, 0xf0, 8);        /* sprite pattern 1: half    */
  vramWriteBytes(0x3b00, sat, (int)sizeof(sat));

  regWrite(0, 0x00);
  regWrite(1, 0xe0); /* 8x8 sprites, no magnification */
  regWrite(2, 0x0e);
  regWrite(3, 0x00);
  regWrite(4, 0x04);
  regWrite(5, 0x76);
  regWrite(6, 0x03);
  regWrite(7, 0xf1); /* white on black */
}

/* F18A unlocked: ECM1 tiles + sprites, two tile layers, scroll registers,
 * 30-row mode (240 lines), scanline-sprite limit raised, 16px sprites */
static void sceneF18aUnlocked(void)
{
  lcgSeed(0x6006);
  vramFillLcg(0x0000, 0x4000);
  unlockF18a();
  paletteWriteLcg(64);
  regWrite(0, 0x00);
  regWrite(1, 0xe2);  /* display on, 16px sprites */
  regWrite(2, 0x0e);  /* T1 name  0x3800 */
  regWrite(3, 0x00);  /* T1 color 0x0000 */
  regWrite(4, 0x04);  /* pattern  0x2000 */
  regWrite(5, 0x76);  /* SAT      0x3b00 */
  regWrite(6, 0x03);  /* SPT      0x1800 */
  regWrite(7, 0xf4);
  regWrite(10, 0x08); /* T2 name  0x2000 */
  regWrite(11, 0x10); /* T2 color 0x0400 */
  regWrite(24, 0x16); /* palette selects: sprites 1, T2 1, T1 2 */
  regWrite(25, 0x0b); /* T2 h-scroll */
  regWrite(26, 0x07); /* T2 v-scroll */
  regWrite(27, 0x05); /* T1 h-scroll */
  regWrite(28, 0x03); /* T1 v-scroll */
  regWrite(29, 0x33); /* page-swap masks + horizontal page sizes */
  regWrite(30, 0x08); /* scanline sprites: 8 */
  regWrite(49, 0xd1); /* T2 on | 30-row | ECM1 tiles | ECM1 sprites */
  regWrite(51, 0x18); /* sprites to process: 24 */
}

